function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
}

function rustLiteral(text) {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n").replace(/\t/g, "\\t")}"`;
}

function countInCode(content, literal) {
  let count = 0;
  let index = 0;
  while ((index = content.indexOf(literal, index)) >= 0) {
    const lineStart = content.lastIndexOf("\n", Math.max(index - 1, 0)) + 1;
    if (!content.slice(lineStart, index).includes("//")) count++;
    index += literal.length;
  }
  return count;
}

function slug(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 80) || "text";
}

function moduleName(file) {
  return file.replace(/^crates\//, "").replace(/\/src\/.*$/, "").replace(/[^a-z0-9_]+/gi, "_");
}

function addPreviousTo(entry, value) {
  if (!value || value === entry.to) return;
  const current = entry.previous_to === undefined ? [] : Array.isArray(entry.previous_to) ? entry.previous_to : [entry.previous_to];
  if (!current.includes(value)) {
    entry.previous_to = [...current, value];
  }
}

