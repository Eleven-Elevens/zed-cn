const translations = readJson(translationsPath);
const rawReport = fs.existsSync(reportPath) ? readJson(reportPath) : [];
const report = Array.isArray(rawReport) ? rawReport : rawReport ? [rawReport] : [];
const usedIds = new Set(translations.map((entry) => entry.id));
const byFileFrom = new Map(translations.map((entry) => [`${entry.file}\0${entry.from}`, entry]));
const contentCache = new Map();
let corrected = 0;
let added = 0;
let skipped = 0;

for (const entry of translations) {
  const correctedTo = corrections.get(entry.from);
  if (correctedTo && correctedTo !== entry.to) {
    const previous = entry.to;
    entry.to = correctedTo;
    addPreviousTo(entry, previous);
    corrected++;
  }
}

if (fs.existsSync(qualityCandidatesPath)) {
  for (const item of readJson(qualityCandidatesPath)) {
    const entry = byFileFrom.get(`${item.file}\0${item.from}`);
    if (entry && corrections.has(entry.from)) {
      addPreviousTo(entry, item.to);
    }
  }
}

for (const entry of manualLiteralEntries) {
  const key = `${entry.file}\0${entry.from}`;
  const existingEntry = byFileFrom.get(key);
  if (existingEntry) {
    if (existingEntry.to !== entry.to) {
      addPreviousTo(existingEntry, existingEntry.to);
      existingEntry.to = entry.to;
      corrected++;
    }
    continue;
  }

  const absolute = path.join(repo, entry.file);
  let content = contentCache.get(entry.file);
  if (content === undefined) {
    content = fs.readFileSync(absolute, "utf8");
    contentCache.set(entry.file, content);
  }

  const expectedCount = countInCode(content, rustLiteral(entry.from));
  if (expectedCount <= 0) {
    skipped++;
    continue;
  }

  const base = entry.id ?? `manual.${moduleName(entry.file)}.${slug(entry.from)}`;
  let id = base;
  let suffix = 2;
  while (usedIds.has(id)) id = `${base}_${suffix++}`;
  usedIds.add(id);

  const next = {
    id,
    file: entry.file,
    from: entry.from,
    to: entry.to,
    expected_count: expectedCount,
  };
  translations.push(next);
  byFileFrom.set(key, next);
  added++;
}

for (const item of report) {
  const translated = corrections.get(item.text);
  if (!translated) continue;
  const key = `${item.file}\0${item.text}`;
  if (byFileFrom.has(key)) continue;

  const absolute = path.join(repo, item.file);
  let content = contentCache.get(item.file);
  if (content === undefined) {
    content = fs.readFileSync(absolute, "utf8");
    contentCache.set(item.file, content);
  }

  const expectedCount = countInCode(content, rustLiteral(item.text));
  if (expectedCount <= 0) {
    skipped++;
    continue;
  }

  const base = `refine.${moduleName(item.file)}.${slug(item.text)}`;
  let id = base;
  let suffix = 2;
  while (usedIds.has(id)) id = `${base}_${suffix++}`;
  usedIds.add(id);

  const entry = {
    id,
    file: item.file,
    from: item.text,
    to: translated,
    expected_count: expectedCount,
  };
  translations.push(entry);
  byFileFrom.set(key, entry);
  added++;
}

for (const entry of manualSourceEntries) {
  const absolute = path.join(repo, entry.file);
  const content = fs.readFileSync(absolute, "utf8");
  const eol = content.includes("\r\n") ? "\r\n" : "\n";
  const normalized = Object.fromEntries(
    Object.entries(entry).map(([key, value]) => [
      key,
      typeof value === "string" ? value.replace(/\n/g, eol) : value,
    ]),
  );
  const key = `${normalized.file}\0${normalized.from}`;
  if (byFileFrom.has(key)) continue;

  const expectedCount = countInCode(content, normalized.from_source);
  if (expectedCount <= 0) {
    skipped++;
    continue;
  }

  let id = entry.id;
  let suffix = 2;
  while (usedIds.has(id)) id = `${entry.id}_${suffix++}`;
  usedIds.add(id);

  const next = {
    id,
    file: normalized.file,
    from: normalized.from,
    to: normalized.to,
    from_source: normalized.from_source,
    to_source: normalized.to_source,
    expected_count: expectedCount,
  };
  translations.push(next);
  byFileFrom.set(key, next);
  added++;
}

fs.writeFileSync(translationsPath, `${JSON.stringify(translations, null, 2)}\n`, "utf8");
